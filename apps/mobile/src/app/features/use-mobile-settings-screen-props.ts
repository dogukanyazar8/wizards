import { useMemo } from "react";
import { createMobileSettingsScreenProps } from "./mobile-settings-screen-props";

type MobileSettingsScreenPropsInput = Parameters<typeof createMobileSettingsScreenProps>[0];

/**
 * The settings tab reads a wide slice of the product app (auth, media, locale,
 * voice, permissions). Building its props inline handed every consumer a new
 * object on unrelated renders — voice-level ticks, typing, realtime backfill —
 * so the assembly lives here with an explicit dependency list instead.
 */
export function useMobileSettingsScreenProps({
  appLockAvailability,
  appLockEnabled,
  authStatusLabel,
  bootstrapState,
  error,
  locale,
  mediaState,
  onOpenCookies,
  onOpenPrivacyPolicy,
  onOpenSupport,
  onOpenTerms,
  onRefreshBootstrap,
  onRefreshSession,
  onRefreshVisibleData,
  onRequestCameraPermission,
  onRequestDocumentPicker,
  onRequestNotificationPermission,
  onRequestPhotoLibraryPermission,
  onSelectLocale,
  onSelectVoiceInputMode,
  onSetAppLockEnabled,
  onSignOut,
  onUpdatePresence,
  openWebRegister,
  openWebSignIn,
  permissionReadiness,
  permissionSummary,
  sessionDiagnostics,
  signedInUserLabel,
  status,
  syncHealth,
  voiceInputMode,
}: MobileSettingsScreenPropsInput) {
  return useMemo(
    () =>
      createMobileSettingsScreenProps({
        appLockAvailability,
        appLockEnabled,
        authStatusLabel,
        bootstrapState,
        error,
        locale,
        mediaState,
        onOpenCookies,
        onOpenPrivacyPolicy,
        onOpenSupport,
        onOpenTerms,
        onRefreshBootstrap,
        onRefreshSession,
        onRefreshVisibleData,
        onRequestCameraPermission,
        onRequestDocumentPicker,
        onRequestNotificationPermission,
        onRequestPhotoLibraryPermission,
        onSelectLocale,
        onSelectVoiceInputMode,
        onSetAppLockEnabled,
        onSignOut,
        onUpdatePresence,
        openWebRegister,
        openWebSignIn,
        permissionReadiness,
        permissionSummary,
        sessionDiagnostics,
        signedInUserLabel,
        status,
        syncHealth,
        voiceInputMode,
      }),
    [
      appLockAvailability,
      appLockEnabled,
      authStatusLabel,
      bootstrapState,
      error,
      locale,
      mediaState,
      onOpenCookies,
      onOpenPrivacyPolicy,
      onOpenSupport,
      onOpenTerms,
      onRefreshBootstrap,
      onRefreshSession,
      onRefreshVisibleData,
      onRequestCameraPermission,
      onRequestDocumentPicker,
      onRequestNotificationPermission,
      onRequestPhotoLibraryPermission,
      onSelectLocale,
      onSelectVoiceInputMode,
      onSetAppLockEnabled,
      onSignOut,
      onUpdatePresence,
      openWebRegister,
      openWebSignIn,
      permissionReadiness,
      permissionSummary,
      sessionDiagnostics,
      signedInUserLabel,
      status,
      syncHealth,
      voiceInputMode,
    ],
  );
}
