/**
 * Regenerates the open-source license manifest the About screen reads.
 *
 * The source of truth is pnpm's own view of the mobile app's production
 * dependency closure — the same resolution that produces the bundle — so the
 * attribution list cannot drift from what actually ships. Run it after any
 * dependency change:
 *
 *   pnpm --filter @wizards/mobile licenses:generate
 */
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

interface PnpmLicenseEntry {
  readonly homepage?: string;
  readonly name?: string;
  readonly versions?: readonly string[];
}

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const mobileRoot = join(scriptDirectory, "..");
const repositoryRoot = join(mobileRoot, "..", "..");
const outputPath = join(mobileRoot, "src", "legal", "mobile-open-source-license-manifest.ts");

function readPnpmLicenses(): Record<string, readonly PnpmLicenseEntry[]> {
  // Corepack selects the pnpm version declared by the workspace. A globally
  // installed pnpm can point at a different store format and cannot reliably
  // inspect this dependency graph. The command is fixed; no input is interpolated.
  const stdout = execSync("corepack pnpm licenses list --json --filter @wizards/mobile --prod", {
    cwd: repositoryRoot,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });

  return JSON.parse(stdout) as Record<string, readonly PnpmLicenseEntry[]>;
}

/** Only a real project page is worth a tap; anything else is dropped. */
function normalizeHomepage(homepage: string | undefined): string | null {
  if (!homepage) {
    return null;
  }

  return /^https?:\/\//i.test(homepage) ? homepage : null;
}

function toManifest(raw: Record<string, readonly PnpmLicenseEntry[]>) {
  return (
    Object.entries(raw)
      .map(([license, entries]) => ({
        license,
        packages: entries
          .flatMap((entry) =>
            entry.name
              ? [
                  {
                    homepage: normalizeHomepage(entry.homepage),
                    name: entry.name,
                    // A package resolved to two versions is still one row; the
                    // reader is being told what is in the app, not how pnpm
                    // deduplicated it.
                    version: [...(entry.versions ?? [])].sort().join(", "),
                  },
                ]
              : [],
          )
          .sort((left, right) => left.name.localeCompare(right.name, "en")),
      }))
      .filter((group) => group.packages.length > 0)
      // Biggest license family first: it is the one most readers are looking for.
      .sort(
        (left, right) =>
          right.packages.length - left.packages.length ||
          left.license.localeCompare(right.license, "en"),
      )
  );
}

function renderModule(groups: ReturnType<typeof toManifest>): string {
  const total = groups.reduce((sum, group) => sum + group.packages.length, 0);

  const body = groups
    .map((group) => {
      const packages = group.packages
        .map(
          (entry) =>
            `      {\n` +
            `        homepage: ${entry.homepage === null ? "null" : JSON.stringify(entry.homepage)},\n` +
            `        name: ${JSON.stringify(entry.name)},\n` +
            `        version: ${JSON.stringify(entry.version)},\n` +
            `      },`,
        )
        .join("\n");

      return (
        `  {\n` +
        `    license: ${JSON.stringify(group.license)},\n` +
        `    packages: [\n${packages}\n    ],\n` +
        `  },`
      );
    })
    .join("\n");

  return (
    `// Generated by scripts/generate-mobile-open-source-licenses.ts — do not edit by hand.\n` +
    `// Source: corepack pnpm licenses list --filter @wizards/mobile --prod\n` +
    `// ${total} packages across ${groups.length} license expressions.\n` +
    `import type { MobileOpenSourceLicenseGroup } from "./mobile-open-source-licenses-model";\n\n` +
    `export const MOBILE_OPEN_SOURCE_LICENSE_GROUPS: readonly MobileOpenSourceLicenseGroup[] = [\n` +
    `${body}\n];\n`
  );
}

const manifest = toManifest(readPnpmLicenses());
if (manifest.length === 0) {
  throw new Error("pnpm reported no production licenses for @wizards/mobile");
}

writeFileSync(outputPath, renderModule(manifest), "utf8");
process.stdout.write(
  `Wrote ${manifest.reduce((sum, group) => sum + group.packages.length, 0)} packages ` +
    `across ${manifest.length} licenses to ${outputPath}\n`,
);
